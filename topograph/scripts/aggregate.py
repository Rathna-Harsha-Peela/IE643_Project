"""Aggregate per-sample metrics into tables (spec §13). Bootstrap 95% CIs (1,000 resamples).

    python scripts/aggregate.py
Reads results/raw/*/*.metrics.jsonl; writes results/tables/*.csv and *.md.
"""
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from tgraph.failures import LABELS  # noqa: E402
from tgraph.io import REPO, read_jsonl  # noqa: E402
from tgraph.metrics import HEADLINE  # noqa: E402
from tgraph.properties import ALL_PROPS  # noqa: E402

TAB = os.path.join(REPO, "results", "tables")
EXTRA = ["node_f1", "edge_f1_aligned", "reach_f1", "kind_multiset_f1", "typed_edge_multiset_f1", "wl_equal"]
VALIDITY = ["parse_ok", "schema_ok", "repaired", "struct_valid", "arity_valid", "code_consistent", "shape_consistent",
            "fully_valid"]
CONFIG_ORDER = ["base2b_fs_c", "coder7b_fs_c", "base9b_zs_c", "base9b_fs_c", "base9b_fs_u", "base9b_fs_c_retry",
                "base9b_think", "base9b_think32k", "base9b_think32k_c", "ceil_zs_c", "ceil_zs_c_retry", "ceil_fs_c",
                "ceil_fs_c_retry", "ft2b_c", "ft2b_c_retry", "ft2b_aug_c", "ft9b_c", "ft9b_u", "ft9b_c_retry", "ft9b_sc5",
                "ft9b_sc5_retry", "ft9b_aug_c"]


def load_all():
    rows = []
    for f in glob.glob(os.path.join(REPO, "results", "raw", "*", "*.metrics.jsonl")):
        rows += read_jsonl(f)
    if not rows:
        return pd.DataFrame()
    df = pd.DataFrame(rows)
    df["config"] = pd.Categorical(df["config"], [c for c in CONFIG_ORDER if c in set(df["config"])] +
                                  sorted(set(df["config"]) - set(CONFIG_ORDER)), ordered=True)
    return df


def boot_ci(x, n=1000, seed=643):
    x = np.asarray(x, dtype=float)
    if len(x) == 0:
        return (np.nan, np.nan)
    rng = np.random.default_rng(seed)
    means = x[rng.integers(0, len(x), (n, len(x)))].mean(1)
    return tuple(np.percentile(means, [2.5, 97.5]))


def fmt(m, lo, hi):
    return f"{100 * m:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]"


def table_with_ci(df, metrics, by):
    out = []
    for keys, g in df.groupby(by, observed=True):
        keys = keys if isinstance(keys, tuple) else (keys,)
        row = dict(zip(by, keys))
        row["n"] = len(g)
        for m in metrics:
            lo, hi = boot_ci(g[m])
            row[m] = g[m].mean()
            row[m + "_lo"], row[m + "_hi"] = lo, hi
        out.append(row)
    return pd.DataFrame(out)


def to_md(t, metrics, by, title):
    lines = [f"## {title}\n", "| " + " | ".join(by + ["n"] + metrics) + " |",
             "|" + "---|" * (len(by) + 1 + len(metrics))]
    for _, r in t.iterrows():
        cells = [str(r[b]) for b in by] + [str(int(r["n"]))]
        cells += [fmt(r[m], r[m + "_lo"], r[m + "_hi"]) for m in metrics]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def simple(df, metrics, by):
    return df.groupby(by, observed=True)[metrics].mean().reset_index()


def paired_diff(df, a, b, eval_set="test", metrics=("edge_f1", "exact_strict", "graph_similarity", "fully_valid")):
    A = df[(df.config == a) & (df.eval_set == eval_set)].set_index("sample_id")
    B = df[(df.config == b) & (df.eval_set == eval_set)].set_index("sample_id")
    common = A.index.intersection(B.index)
    if not len(common):
        return None
    out = {"a": a, "b": b, "eval_set": eval_set, "n": len(common)}
    for m in metrics:
        d = A.loc[common, m].astype(float).values - B.loc[common, m].astype(float).values
        lo, hi = boot_ci(d)
        out[m] = {"diff": float(d.mean()), "ci95": [float(lo), float(hi)]}
    return out


def main():
    os.makedirs(TAB, exist_ok=True)
    df = load_all()
    if df.empty:
        print("no metrics files yet")
        return
    md = ["# Results tables\n", "Generated by `scripts/aggregate.py` from `results/raw/*/*.metrics.jsonl`. "
          "Values are % (mean over samples) with bootstrap 95% CIs. The torch.fx oracle scores 100% on every "
          "traceable set by construction (it produced the labels).\n"]
    test = df[df.eval_set == "test"]
    main_t = table_with_ci(test, HEADLINE, ["config"])
    main_t.to_csv(os.path.join(TAB, "main.csv"), index=False)
    md.append(to_md(main_t, HEADLINE, ["config"], "Main: official test (1,000)"))
    allsets = table_with_ci(df, ["fully_valid", "edge_f1", "exact_strict", "isomorphic", "graph_similarity"],
                            ["config", "eval_set"])
    allsets.to_csv(os.path.join(TAB, "by_eval_set.csv"), index=False)
    md.append(to_md(allsets, ["fully_valid", "edge_f1", "exact_strict", "isomorphic", "graph_similarity"],
                    ["config", "eval_set"], "All eval sets"))
    with open(os.path.join(TAB, "main.md"), "w") as f:
        f.write("\n".join(md))

    core = HEADLINE + EXTRA
    simple(test, core, ["config", "tier"]).to_csv(os.path.join(TAB, "by_tier.csv"), index=False)
    simple(df[df.eval_set.isin(["test", "test_anon"])], core, ["config", "eval_set", "augmentation_type"]).to_csv(
        os.path.join(TAB, "by_aug.csv"), index=False)
    simple(test, core, ["config", "size_bin"]).to_csv(os.path.join(TAB, "by_size.csv"), index=False)
    seen = df[df.eval_set.isin(["test", "novel_topo", "ood", "ood2"])].copy()
    seen["slice"] = np.where(seen.eval_set != "test", seen.eval_set,
                             np.where(seen.struct_seen.astype(bool), "test_seen", "test_unseen"))
    simple(seen, core, ["config", "slice"]).to_csv(os.path.join(TAB, "seen_vs_unseen.csv"), index=False)
    ood = df[df.eval_set.isin(["ood", "ood2"])]
    if len(ood):
        simple(ood, core, ["config", "eval_set", "category"]).to_csv(os.path.join(TAB, "ood_by_category.csv"), index=False)
    simple(df, [f"prop_{p}" for p in ALL_PROPS] + ["pps"], ["config", "eval_set"]).to_csv(
        os.path.join(TAB, "properties.csv"), index=False)
    v = simple(df, VALIDITY + ["dead_code_included"], ["config", "eval_set"])
    hall = df.groupby(["config", "eval_set"], observed=True).apply(
        lambda g: g.n_undeclared.sum() / max(1, g.n_call_module.sum()), include_groups=False).rename("hallucination_rate")
    v = v.merge(hall.reset_index(), on=["config", "eval_set"])
    dead = df[df.augmentation_type.isin(["aug_variant_2", "aug_variant_3"])].groupby(
        ["config", "eval_set"], observed=True).dead_code_included.mean().rename("dead_code_inclusion_rate").reset_index()
    v = v.merge(dead, on=["config", "eval_set"], how="left")
    v.to_csv(os.path.join(TAB, "validity.csv"), index=False)
    fl = df.explode("failures")
    fl = fl[fl.failures.notna()]
    if len(fl):
        fc = fl.groupby(["config", "eval_set", "tier", "failures"], observed=True).size().rename("count").reset_index()
        fc.to_csv(os.path.join(TAB, "failures.csv"), index=False)
    retry = df[df.config.astype(str).str.contains("retry")]
    if len(retry):
        r = retry.groupby(["config", "eval_set"], observed=True).agg(
            initial_fully_valid=("initial_fully_valid", "mean"), final_fully_valid=("fully_valid", "mean"),
            mean_rounds=("rounds_used", "mean"), n=("sample_id", "size")).reset_index()
        r.to_csv(os.path.join(TAB, "retry.csv"), index=False)
    pairs = [("ft9b_c", "base9b_fs_c"), ("ft9b_c", "base9b_zs_c"), ("ft2b_c", "base2b_fs_c"), ("ft9b_c", "ft2b_c"),
             ("ft9b_c", "ft9b_u"), ("base9b_fs_c", "base9b_fs_u")]
    paired = [p for p in (paired_diff(df, a, b, s) for a, b in pairs for s in ("test", "novel_topo", "ood")) if p]
    with open(os.path.join(TAB, "paired.json"), "w") as f:
        json.dump(paired, f, indent=1)
    print(open(os.path.join(TAB, "main.md")).read()[:3000])


if __name__ == "__main__":
    main()
